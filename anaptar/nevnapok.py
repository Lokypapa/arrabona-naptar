def _key(day):
    """MM-DD kulcs; szökőévben febr. 24. szökőnap (None), utána egy nappal csúszik."""
    if day.month == 2 and _leap(day.year):
        if day.day == 24:
            return None
        if day.day > 24:
            return "02-%02d" % (day.day - 1)
    return day.strftime("%m-%d")


def _leap(y):
    return y % 4 == 0 and (y % 100 != 0 or y % 400 == 0)


def names_for(day):
    """A nap fő névnapjai (lista). Szökőévben február 24. szökőnap."""
    k = _key(day)
    return list(NEVNAPOK.get(k, [])) if k else []


