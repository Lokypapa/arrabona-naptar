def find_name(name, year=None):
    """Mikor van X névnapja? Visszaad: dátumok listája (az adott évben). Becenévvel is működik."""
    year = year or datetime.date.today().year
    q = _fold(name.strip())
    out = []
    if not q:
        return out
    full = next((v for k, v in BECENEVEK.items() if _fold(k) == q), None)
    if full and not any(_fold(n) == q for n in all_names()):
        q = _fold(full)
    day = datetime.date(year, 1, 1)
    while day.year == year:
        if any(_fold(n) == q for n in all_names_for(day)):
            out.append(day)
        day += datetime.timedelta(days=1)
    return out


def all_names():
    s = set(BOVITETT)
    for v in NEVNAPOK.values():
        s.update(v)
    return sorted(s, key=_fold)


def resolve(name):
    """Becenév -> naptári név (ha van), különben a név maga."""
    q = _fold(name.strip())
    for n in all_names():
        if _fold(n) == q:
            return n
    return next((v for k, v in BECENEVEK.items() if _fold(k) == q), name.strip())
