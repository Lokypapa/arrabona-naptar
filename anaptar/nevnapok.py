def extra_names_for(day):
    """A nap bővített névnaptárbeli nevei (a fő névnapokon felül)."""
    k = _key(day)
    return sorted(_EXTRA_BY_DAY.get(k, []), key=lambda s: s.casefold()) if k else []


def all_names_for(day):
    return names_for(day) + extra_names_for(day)


def _fold(s):
    import unicodedata
    s = unicodedata.normalize("NFD", s.casefold())
    return "".join(c for c in s if unicodedata.category(c) != "Mn")


